/* --- Selectors -------------------------------------------------------------
   Kept next to the data so the query layer and the UI agree on the rules. */

export function getPlaceBySlug(slug: string): Place | undefined {
  return PLACES.find((place) => place.slug === slug)
}

export function getPlaceById(id: string): Place | undefined {
  return PLACES.find((place) => place.id === id)
}

export function getPlacesByCategory(category: Place['category']): Place[] {
  return PLACES.filter((place) => place.category === category)
}

export function getFeaturedPlaces(limit = 6): Place[] {
  return PLACES.filter((place) => place.isFeatured).slice(0, limit)
}

/** Cities that appear in the catalogue, for the (future) destination filter. */
export function getCities(): string[] {
  return [...new Set(PLACES.map((place) => place.city))].sort()
}
